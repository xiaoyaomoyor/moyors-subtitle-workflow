import {test,expect} from '@playwright/test';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {disableOnboarding,findFreePort,makeTempDir,startBlankServer} from './helpers.mjs';
import {setLauncherLanguage} from './launcher-language.mjs';
let server,root;
test.beforeEach(async({page})=>{
  root=makeTempDir('asr-presets');process.env.MAW_ENV_FILE=join(root,'synthetic.env');process.env.MSW_APP_DATA_ROOT=join(root,'app-data');
  server=await startBlankServer(await findFreePort(),join(root,'settings'));
  await disableOnboarding(page);await page.goto(server.url);await expect(page.locator('.waveform-row').first()).toBeVisible();
  await page.evaluate(()=>MSWE.resolve('asr').open());
  await expect(page.locator('#msw-asr-presets [data-action="library"]')).toBeEnabled({timeout:15000});
});
test.afterEach(async()=>{await server?.stop();});
const panel=page=>page.locator('#msw-asr-presets');
const library=page=>page.locator('.msw-asr-library');
async function create(page,name='节目 A'){
  await panel(page).locator('[data-action="library"]').click();
  await library(page).locator('[data-role="name"]').fill(name);
  await library(page).locator('[data-role="description"]').fill('角色与剧情背景');
  await library(page).locator('[data-command="new"]').click();
  await expect(library(page).locator('.asr-preset-item')).toContainText(name);
}
test('editor library previews, explicitly loads, tracks edits, restores deleted items and transfers configuration',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.locator('#msw-asr-modelId').selectOption('qwen-audio-3.1-asr-flash-filetrans');
  await panel(page).locator('.asr-background > summary').click();
  await panel(page).locator('[data-role="background"]').fill('主角叫小明，故事发生在银港。');
  await page.locator('#msw-asr-settings > details > summary').click();
  await page.locator('#msw-asr-gapSplit').fill('500');
  await page.locator('#msw-asr-qwenKeepDialect').check();
  await create(page);
  await page.screenshot({path:info.outputPath('asr-library-editor-zh.png')});
  await library(page).locator('[data-command="close"]').click();
  await page.locator('#msw-asr-gapSplit').fill('800');
  await expect(panel(page).locator('[data-role="current"]')).toContainText('已修改');
  await panel(page).locator('[data-action="library"]').click();
  await library(page).locator('.asr-preset-item').click();
  await expect(page.locator('#msw-asr-gapSplit')).toHaveValue('800');
  await library(page).locator('[data-command="load"]').click();
  await expect(page.locator('#msw-asr-gapSplit')).toHaveValue('500');
  await expect(page.locator('#msw-asr-modelId')).toHaveValue('qwen-audio-3.1-asr-flash-filetrans');
  expect(await page.evaluate(()=>MSWE.resolve('asr').jobs.length)).toBe(0);
  await page.locator('#msw-asr-gapSplit').fill('650');
  await panel(page).locator('[data-action="library"]').click();
  await library(page).locator('[data-command="update"]').click();
  await expect(library(page).locator('[data-role="preview"]')).toContainText('650');
  await library(page).locator('[data-role="search"]').fill('不存在');
  await expect(library(page).locator('.asr-preset-item')).toHaveCount(0);
  await library(page).locator('[data-role="search"]').fill('节目');
  await expect(library(page).locator('.asr-preset-item')).toHaveCount(1);
  await library(page).locator('[data-command="copy"]').click();
  await expect(library(page).locator('.asr-preset-item')).toHaveCount(2);
  await library(page).locator('[data-role="name"]').fill('节目 B');
  await library(page).locator('[data-command="rename"]').click();
  await library(page).locator('[data-command="delete"]').click();
  await expect(library(page).locator('.asr-preset-item')).toHaveCount(1);
  await library(page).locator('[data-role="deleted"]').check();
  await library(page).locator('.asr-preset-item').click();
  await library(page).locator('[data-command="restore"]').click();
  await expect(library(page).locator('.asr-preset-item')).toHaveCount(0);
  const transfer=await page.evaluate(()=>MSWConfig.request({action:'export',categories:['asr']}));
  expect(transfer.package.sections.asr.presets).toHaveLength(2);
  for(const row of transfer.package.sections.asr.presets)expect(Object.keys(row.options)).not.toEqual(expect.arrayContaining(['apiKey','localModelPath']));
  await library(page).locator('[data-command="close"]').click();
  await page.setViewportSize({width:420,height:800});await page.evaluate(()=>MSWE_I18N.applyLanguage('en'));
  await panel(page).locator('[data-action="library"]').click();
  await library(page).locator('[data-role="deleted"]').uncheck();
  await library(page).locator('.asr-preset-item').first().click();
  await expect(library(page).locator('header')).toContainText('Recognition presets');
  expect(await library(page).evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:info.outputPath('asr-library-editor-en-narrow.png')});
  expect(errors).toEqual([]);
});
test('launcher and editor share the real library and preserve a dedicated prompt without changing providers',async({page,context},info)=>{
  await panel(page).locator('.asr-background > summary').click();
  await panel(page).locator('[data-role="background"]').fill('共同背景');
  await panel(page).locator('.asr-background details > summary').click();
  await panel(page).locator('[data-override="openai"]').check();
  await panel(page).locator('[data-override-text="openai"]').fill('OpenAI 专用文本');
  await panel(page).locator('[data-action="save-prompts"]').click();
  await expect(panel(page).locator('[data-role="prompt-state"]')).toHaveText('已保存');
  await create(page);await library(page).locator('[data-command="close"]').click();
  const launcher=await context.newPage(),errors=[];launcher.on('pageerror',e=>errors.push(e.message));
  await launcher.exposeFunction('presetRequest',payload=>page.evaluate(payload=>MSWE.resolve('media').request('asr-presets',payload),payload));
  await launcher.addInitScript(()=>document.addEventListener('DOMContentLoaded',()=>{
    MSWLauncher.bridgeOverride=async(method,payload,next)=>method==='asr_presets'?{ok:true,...await window.presetRequest(payload)}:next(method,payload);
  },{once:true}));
  await launcher.goto(pathToFileURL(resolve('web/launcher/index.html')).href);
  await launcher.waitForFunction(()=>MSWLauncher.config?.providers?.length&&document.querySelector('#prefabRail input'));
  await launcher.evaluate(()=>MSWNavigation.show('prefab'));
  await launcher.locator('#prefabRail input[data-module-id="asr"]').check();
  if(await launcher.locator('#recognitionCard').evaluate(el=>el.classList.contains('collapsed')))await launcher.locator('#recognitionCard .module-collapse').click();
  const ui=launcher.locator('#launcherAsrPresets');
  await expect(ui.locator('[data-action="library"]'),await ui.textContent()).toBeEnabled();
  await ui.locator('[data-action="library"]').click();
  await library(launcher).locator('.asr-preset-item').click();
  const provider=await launcher.locator('#provider').inputValue(),model=await launcher.locator('#model').inputValue();
  await library(launcher).locator('[data-command="load"]').click();
  await expect(launcher.locator('#provider')).toHaveValue(provider);await expect(launcher.locator('#model')).toHaveValue(model);
  const value=await launcher.evaluate(()=>MSWLauncher.getTranscriptionPayload().asrPrompts);
  expect(value).toEqual({text:'共同背景',overrides:{openai:'OpenAI 专用文本'}});
  await ui.locator('.asr-background > summary').click();
  await ui.locator('[data-role="background"]').fill('跨窗口更新');await ui.locator('[data-action="save-prompts"]').click();
  await expect(ui.locator('[data-role="prompt-state"]')).toHaveText('已保存');
  await panel(page).locator('[data-role="background"]').fill('保留本窗口草稿');
  await panel(page).locator('[data-action="save-prompts"]').click();
  await expect(panel(page).locator('[data-role="message"]')).toContainText('其他窗口');
  await expect(panel(page).locator('[data-role="background"]')).toHaveValue('保留本窗口草稿');
  await setLauncherLanguage(launcher,'en');await ui.locator('[data-action="library"]').click();
  await expect(library(launcher)).toBeVisible();
  await expect(library(launcher).locator('[data-command="load"]')).toBeEnabled();
  await expect(library(launcher).locator('header')).toContainText('Recognition presets');
  expect((await library(launcher).locator('[data-role="deleted"]').boundingBox()).width).toBeLessThanOrEqual(18);
  await launcher.screenshot({path:info.outputPath('asr-library-launcher-en.png')});
  expect(errors).toEqual([]);await launcher.close();
});
